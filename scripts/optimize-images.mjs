async function download(id) {
  const out = path.join(UNSPLASH_DIR, `${id}.jpg`);
  if (existsSync(out)) return out;
  const url = `https://images.unsplash.com/${id}?fm=jpg&fit=max&w=${MAX_WIDTH}&q=90`;
  const res = await fetch(url, { headers: { 'user-agent': 'Mozilla/5.0' } });
  if (!res.ok) throw new Error(`${id}: HTTP ${res.status}`);
  await writeFile(out, Buffer.from(await res.arrayBuffer()));
  return out;
}

async function compress(file) {
  const before = (await stat(file)).size;
  const buf = await sharp(file)
    .rotate()
    .resize({ width: MAX_WIDTH, withoutEnlargement: true })
    .jpeg({ quality: JPEG_QUALITY, mozjpeg: true, progressive: true, chromaSubsampling: '4:2:0' })
    .toBuffer();
  await writeFile(file, buf);
  return { before, after: buf.length };
}

async function blur(file) {
  const buf = await sharp(file).resize(12).jpeg({ quality: 40 }).toBuffer();
  return `data:image/jpeg;base64,${buf.toString('base64')}`;
}

async function* walk(dir) {
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) yield* walk(p);
    else if (/\.(jpe?g)$/i.test(e.name)) yield p;
  }
}

await mkdir(UNSPLASH_DIR, { recursive: true });
await Promise.all(UNSPLASH_IDS.map((id) => download(id).then(() => console.log('downloaded', id))));

const entries = [];
for await (const file of walk(PUBLIC_IMAGES)) {
  const { before, after } = await compress(file);
  const rel = '/' + path.relative(path.join(ROOT, 'public'), file).split(path.sep).join('/');
  entries.push([rel, await blur(file)]);
  console.log(`${rel}: ${(before / 1024).toFixed(0)}KB -> ${(after / 1024).toFixed(0)}KB`);
}
entries.sort(([a], [b]) => a.localeCompare(b));

const ts = `// Generated by scripts/optimize-images.mjs — do not edit by hand.
// Tiny base64 JPEG placeholders (12px wide) keyed by public image path.
export const BLUR_DATA: Record<string, string> = {
${entries.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n')}
};
`;
await writeFile(path.join(ROOT, 'lib/blur-data.ts'), ts);
console.log(`wrote lib/blur-data.ts (${entries.length} images)`);
