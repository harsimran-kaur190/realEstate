/**
 * One-off image pipeline for Altiere Estates.
 *
 *  1. Downloads every Unsplash photo the site references into
 *     public/images/unsplash/<id>.jpg so nothing is fetched from a
 *     third-party CDN at request time.
 *  2. Re-encodes every JPEG under public/images to a 1600px-wide,
 *     progressive, mozjpeg-compressed file (sources were ~800KB each).
 *  3. Emits lib/blur-data.ts: a tiny base64 blur placeholder per image so
 *     <Image placeholder="blur"> paints instantly before bytes arrive.
 *
 * Run:  node scripts/optimize-images.mjs
 * `sharp` is already installed transitively by Next.js.
 */
